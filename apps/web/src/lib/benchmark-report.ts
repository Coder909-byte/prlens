import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const REPORTS_DIR = join(process.cwd(), "..", "..", "evals", "reports");

export interface AggregateStats {
  pairCount: number;
  recall: number;
  fpPerPr: number;
  avgCostUsd: number | null;
  totalCostUsd: number | null;
  p50LatencyMs: number;
  p95LatencyMs: number;
  failedCount: number;
}

export interface ComparisonPairRow {
  id: string;
  repo: string;
  method: string;
  confidence: string;
  diffOnlyCaught: boolean;
  diffOnlyCostUsd: number | null;
  diffOnlyLatencyMs: number;
  repoAwareCaught: boolean;
  repoAwareCostUsd: number | null;
  repoAwareLatencyMs: number;
  divergenceNote: string | null;
}

export interface ComparisonReport {
  generatedAt: string;
  split: string;
  provider: string;
  model: string;
  splitNote: string;
  overall: {
    diffOnly: AggregateStats;
    repoAware: AggregateStats;
    extraInputTokensAvg: number;
    extraCostUsd: number;
  };
  byRepo: Record<string, { diffOnly: AggregateStats; repoAware: AggregateStats }>;
  pairs: ComparisonPairRow[];
}

/** Reads the most recently generated evals/reports/*-comparison-*.json - regenerated by `pnpm eval:compare`, committed to git. Returns null if none exists yet (e.g. a fresh checkout before the eval has ever run). */
export function loadLatestComparisonReport(): ComparisonReport | null {
  let files: string[];
  try {
    files = readdirSync(REPORTS_DIR).filter((f) => /-comparison-(dev|test)\.json$/.test(f));
  } catch {
    return null;
  }
  if (files.length === 0) return null;
  const newest = files.sort().at(-1)!;
  return JSON.parse(readFileSync(join(REPORTS_DIR, newest), "utf8")) as ComparisonReport;
}
